# 统计分类
from collections import Counter
cats = Counter(d["category"] for d in docs)
print("\n分类统计:")
for cat, count in cats.most_common():
    print(f"  {cat}: {count} 篇")

# 生成对应的测试问答对
qa_pairs = []
for d in docs:
    cat = d["category"]
    title = d["title"]
    # 为每篇文档生成2-3个查询
    kw = d.get("keywords", [])
    qa_pairs.append({
        "query": f"关于{kw[0] if kw else title.split('：')[-1]}的问题",
        "expected_category": cat,
        "expected_doc_title": title,
    })

print(f"\n生成 {len(qa_pairs)} 个测试问答对")
