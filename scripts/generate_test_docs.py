def save_docs(docs):
    filepath = os.path.join(OUTPUT_DIR, "test_documents.json")
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(docs, f, ensure_ascii=False, indent=2)

    print(f"生成 {len(docs)} 篇文档 -> {filepath}")

    total_chars = sum(len(d["content"]) for d in docs)
    print(f"总字符数: {total_chars:,}")

    categories = {}
    for d in docs:
        cat = d["category"]
        categories[cat] = categories.get(cat, 0) + 1
    print(f"文档分类: {json.dumps(categories, ensure_ascii=False)}")

